// Imports AI-generated card illustrations into the game.
//   npx tsx scripts/art/import.ts <folder-or-files...>
// Files must be named after the card id (pumpar.png, bunkr.jpg, …). Zip files are extracted first.
// Output: public/art/<id>.webp (portrait 720x1080, landscape 1080x720) + src/client/gen/art.ts manifest.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, extname, join } from 'node:path';
import sharp from 'sharp';
import { ART } from './prompts';

const OUT = 'public/art';
mkdirSync(OUT, { recursive: true });

function collect(p: string, acc: string[]) {
  if (!existsSync(p)) return;
  const st = statSync(p);
  if (st.isDirectory()) {
    for (const f of readdirSync(p)) collect(join(p, f), acc);
  } else if (/\.zip$/i.test(p)) {
    const dir = mkdtempSync(join(tmpdir(), 'pk-art-'));
    execFileSync('unzip', ['-q', '-o', p, '-d', dir]);
    collect(dir, acc);
  } else if (/\.(png|jpe?g|webp)$/i.test(p)) {
    acc.push(p);
  }
}

/** "Pumpar (1).PNG" -> "pumpar"; also accepts Czech names without diacritics. */
function idFor(file: string): string | null {
  const raw = basename(file, extname(file)).toLowerCase().replace(/\s*\(\d+\)$/, '').replace(/[-_ ]?\d+$/, '').trim();
  const plain = raw.normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]/g, '');
  if (ART[plain]) return plain;
  for (const id of Object.keys(ART)) if (plain.startsWith(id)) return id;
  return null;
}

const files: string[] = [];
for (const a of process.argv.slice(2)) collect(a, files);
if (!files.length) {
  console.error('Nenašel jsem žádné obrázky. Použití: npx tsx scripts/art/import.ts <složka|soubory|zip>');
  process.exit(1);
}

let ok = 0;
const skipped: string[] = [];
for (const f of files) {
  const id = idFor(f);
  if (!id) { skipped.push(basename(f)); continue; }
  const land = !!ART[id].landscape;
  const big = id === 'playmat';
  await sharp(f)
    .resize(big ? 1920 : land ? 1080 : 720, big ? 1080 : land ? 720 : 1080, { fit: 'cover', position: big ? 'centre' : sharp.strategy.attention })
    .webp({ quality: 80, effort: 5 })
    .toFile(join(OUT, `${id}.webp`));
  ok++;
  console.log(`✓ ${basename(f)} → ${OUT}/${id}.webp`);
}

const have = readdirSync(OUT).filter((f) => f.endsWith('.webp')).map((f) => f.replace(/\.webp$/, '')).filter((id) => ART[id]).sort();
mkdirSync('src/client/gen', { recursive: true });
writeFileSync('src/client/gen/art.ts',
  `// AUTO-GENERATED by scripts/art/import.ts – do not edit.\n` +
  `export const ART_VERSION = '${Date.now().toString(36)}';\n` +
  `export const ART_IDS: ReadonlySet<string> = new Set(${JSON.stringify(have)});\n`);
console.log(`\nImportováno ${ok} obrázků, ve hře je teď ${have.length}/${Object.keys(ART).length} ilustrací.`);
if (skipped.length) console.log(`Přeskočeno (neznámý název): ${skipped.join(', ')}`);
const missing = Object.keys(ART).filter((id) => !have.includes(id));
if (missing.length) console.log(`Chybí: ${missing.join(', ')}`);
