// Extracts the game-icons.net glyphs we use (CC BY 3.0, by Lorc, Delapouite & contributors)
// into a small TS module so the client does not ship all 4000+ icons.
//   npm run icons

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { ALL_CARDS } from '../src/engine/cards';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/game-icons/icons.json') as { icons: Record<string, { body: string }>; aliases?: Record<string, { parent: string }> };

export const UI_ICONS = [
  'water-drop', 'crosshair', 'human-target', 'bandage-roll', 'card-play', 'hooded-figure', 'flaming-claw',
  'broken-skull', 'stun-grenade', 'time-dynamite', 'hourglass', 'return-arrow', 'chat-bubble', 'speaker',
  'speaker-off', 'rule-book', 'trophy-cup', 'death-skull', 'oil-drum', 'hamburger-menu', 'info', 'check-mark',
  'cross-mark', 'exit-door', 'gas-mask', 'night-sleep', 'barrel', 'cog', 'coinflip', 'eye-target', 'play-button',
  'stockpiles', 'explosion-rays', 'desert', 'podium-winner', 'robot-golem', 'tabletop-players',
  'wifi-router', 'padlock', 'shield', 'sun', 'magnifying-glass', 'broken-shield', 'swap-bag', 'card-draw',
  'crossed-swords', 'cracked-shield', 'heart-drop', 'knockout', 'checkered-flag', 'sands-of-time',
  'focused-lightning', 'stopwatch', 'windpump', 'sandstorm',
];

const names = new Set<string>([...UI_ICONS, ...ALL_CARDS.map((c) => c.icon)]);
const out: Record<string, string> = {};
const missing: string[] = [];
for (const n of names) {
  let key = n;
  if (!set.icons[key] && set.aliases?.[key]) key = set.aliases[key].parent;
  const ic = set.icons[key];
  if (!ic) { missing.push(n); continue; }
  out[n] = ic.body;
}
if (missing.length) console.warn('Missing icons:', missing.join(', '));
mkdirSync('src/client/gen', { recursive: true });
writeFileSync(
  'src/client/gen/icons.ts',
  `// AUTO-GENERATED by scripts/build-icons.ts – do not edit.\n// Icons from game-icons.net (CC BY 3.0) – Lorc, Delapouite and contributors.\n` +
  `export const ICONS: Record<string, string> = ${JSON.stringify(out, null, 0)};\n`,
);
console.log(`Wrote ${Object.keys(out).length} icons (${Math.round(readFileSync('src/client/gen/icons.ts').length / 1024)} KB).`);
